package com.example.services

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import org.json.JSONObject
import java.util.concurrent.TimeUnit

data class GitHubBuildRun(
    val id: Long,
    val name: String,
    val status: String,
    val conclusion: String,
    val htmlUrl: String,
    val createdAt: String
)

class GitHubBuildService {

    private val client = OkHttpClient.Builder()
        .connectTimeout(15, TimeUnit.SECONDS)
        .readTimeout(20, TimeUnit.SECONDS)
        .build()

    fun generateAndroidBuildWorkflowYaml(
        appName: String,
        packageName: String,
        versionName: String,
        buildType: String
    ): String {
        val gradleTask = if (buildType.contains("Release", ignoreCase = true)) {
            "./gradlew bundleRelease"
        } else {
            "./gradlew assembleDebug"
        }
        val artifactPath = if (buildType.contains("Release", ignoreCase = true)) {
            "app/build/outputs/bundle/release/*.aab"
        } else {
            "app/build/outputs/apk/debug/*.apk"
        }

        return """
            # Generated by Jarvis AI Android APK Build Manager
            # App: $appName ($packageName) v$versionName
            name: Android Build ($buildType)

            on:
              workflow_dispatch:
                inputs:
                  version_name:
                    description: 'Version Name'
                    default: '$versionName'
                    required: false

            jobs:
              build-android:
                runs-on: ubuntu-latest
                steps:
                  - name: Checkout repository
                    uses: actions/checkout@v4

                  - name: Set up JDK 17
                    uses: actions/setup-java@v4
                    with:
                      distribution: 'temurin'
                      java-version: '17'

                  - name: Grant Gradle execute permission
                    run: chmod +x gradlew

                  - name: Build Android Artifact ($buildType)
                    run: $gradleTask

                  - name: Upload Verified Build Artifact
                    uses: actions/upload-artifact@v4
                    with:
                      name: ${packageName.replace('.', '-')}-${buildType.lowercase().replace(' ', '-')}
                      path: $artifactPath
        """.trimIndent()
    }

    suspend fun triggerWorkflowDispatch(
        ownerRepo: String,
        workflowFile: String,
        token: String,
        branch: String = "main"
    ): Result<String> = withContext(Dispatchers.IO) {
        if (ownerRepo.isBlank() || !ownerRepo.contains("/") || token.isBlank()) {
            return@withContext Result.failure(
                IllegalStateException("SETUP REQUIRED – CONNECT GITHUB REPOSITORY (owner/repo) AND PAT TOKEN.")
            )
        }
        try {
            val url = "https://api.github.com/repos/$ownerRepo/actions/workflows/$workflowFile/dispatches"
            val bodyJson = JSONObject().put("ref", branch).toString()
            val request = Request.Builder()
                .url(url)
                .header("Accept", "application/vnd.github+json")
                .header("Authorization", "Bearer $token")
                .header("X-GitHub-Api-Version", "2022-11-28")
                .post(bodyJson.toRequestBody("application/json".toMediaType()))
                .build()

            client.newCall(request).execute().use { resp ->
                if (resp.isSuccessful) {
                    Result.success("Workflow '$workflowFile' dispatched on $ownerRepo ($branch). Refresh runs to track real build status.")
                } else {
                    val err = resp.body?.string().orEmpty().take(240)
                    Result.failure(IllegalStateException("GitHub API ${resp.code}: $err"))
                }
            }
        } catch (e: Exception) {
            Result.failure(e)
        }
    }

    suspend fun fetchWorkflowRuns(
        ownerRepo: String,
        token: String
    ): Result<List<GitHubBuildRun>> = withContext(Dispatchers.IO) {
        if (ownerRepo.isBlank() || !ownerRepo.contains("/") || token.isBlank()) {
            return@withContext Result.failure(
                IllegalStateException("SETUP REQUIRED – CONNECT GITHUB REPOSITORY AND PAT TOKEN.")
            )
        }
        try {
            val url = "https://api.github.com/repos/$ownerRepo/actions/runs?per_page=8"
            val request = Request.Builder()
                .url(url)
                .header("Accept", "application/vnd.github+json")
                .header("Authorization", "Bearer $token")
                .header("X-GitHub-Api-Version", "2022-11-28")
                .get()
                .build()

            client.newCall(request).execute().use { resp ->
                if (!resp.isSuccessful) {
                    return@withContext Result.failure(IllegalStateException("GitHub API error ${resp.code}"))
                }
                val json = JSONObject(resp.body?.string().orEmpty())
                val runs = json.optJSONArray("workflow_runs")
                val list = mutableListOf<GitHubBuildRun>()
                if (runs != null) {
                    for (i in 0 until runs.length()) {
                        val r = runs.optJSONObject(i) ?: continue
                        list.add(
                            GitHubBuildRun(
                                id = r.optLong("id", 0L),
                                name = r.optString("name", "Android Build"),
                                status = r.optString("status", "unknown"),
                                conclusion = r.optString("conclusion", "in_progress"),
                                htmlUrl = r.optString("html_url", ""),
                                createdAt = r.optString("created_at", "")
                            )
                        )
                    }
                }
                Result.success(list)
            }
        } catch (e: Exception) {
            Result.failure(e)
        }
    }
}
